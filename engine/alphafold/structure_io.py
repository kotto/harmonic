# Mapping PDB atom names → residue atom names
PDB_BACKBONE_ATOMS = {'N', 'CA', 'C', 'O'}

# Codes 3 lettres → 1 lettre
AA3TO1 = {
    'ALA': 'A', 'ARG': 'R', 'ASN': 'N', 'ASP': 'D', 'CYS': 'C',
    'GLN': 'Q', 'GLU': 'E', 'GLY': 'G', 'HIS': 'H', 'ILE': 'I',
    'LEU': 'L', 'LYS': 'K', 'MET': 'M', 'PHE': 'F', 'PRO': 'P',
    'SER': 'S', 'THR': 'T', 'TRP': 'W', 'TYR': 'Y', 'VAL': 'V',
}

AA1TO3 = {v: k for k, v in AA3TO1.items()}


def parse_pdb(filepath: str) -> ProteinStructure:
    """
    Parse un fichier PDB et extrait les atomes du backbone.

    Args:
        filepath: chemin vers le fichier PDB

    Returns:
        ProteinStructure avec les coordonnées des atomes
    """
    with open(filepath, 'r') as f:
        lines = f.readlines()

    # Extraire les atomes
    atoms = {}  # (residue_index, atom_name) -> position
    residue_types = {}  # residue_index -> code1
    residue_indices = set()

    for line in lines:
        if line.startswith('ATOM') or line.startswith('HETATM'):
            atom_name = line[12:16].strip()
            res_name = line[17:20].strip()
            res_idx = int(line[22:26].strip())
            x = float(line[30:38])
            y = float(line[38:46])
            z = float(line[46:54])

            if res_idx not in residue_types:
                residue_types[res_idx] = AA3TO1.get(res_name, 'X')
            residue_indices.add(res_idx)

            atoms[(res_idx, atom_name)] = np.array([x, y, z])

    if not residue_indices:
        raise ValueError("Aucun atome trouvé dans le fichier PDB")

    # Ordonner les résidus
    sorted_indices = sorted(residue_indices)

    # Construire la séquence
    sequence = ''.join(residue_types.get(i, 'X') for i in sorted_indices)

    # Construire la structure
    residues = []
    for i, res_idx in enumerate(sorted_indices):
        aa = get_amino_acid(residue_types.get(res_idx, 'X'))
        if aa is None:
            aa = get_amino_acid('G')  # fallback

        N = atoms.get((res_idx, 'N'), np.zeros(3))
        CA = atoms.get((res_idx, 'CA'), np.zeros(3))
        C = atoms.get((res_idx, 'C'), np.zeros(3))
        O = atoms.get((res_idx, 'O'), np.zeros(3))

        # Extraire les atomes de chaîne latérale
        sidechain = {}
        for (r_idx, name), pos in atoms.items():
            if r_idx == res_idx and name not in PDB_BACKBONE_ATOMS:
                sidechain[name] = pos

        res = ResidueAtoms(index=i, aa=aa, N=N, CA=CA, C=C, O=O,
                          sidechain=sidechain)
        residues.append(res)

    structure = ProteinStructure(sequence=sequence, residues=residues)

    # Calculer φ et ψ
    from .peptide_geometry import dihedral_angle
    for i in range(1, len(residues)):
        residues[i].phi = math.degrees(dihedral_angle(
            residues[i-1].C, residues[i].N, residues[i].CA, residues[i].C))
    for i in range(len(residues) - 1):
        residues[i].psi = math.degrees(dihedral_angle(
            residues[i].N, residues[i].CA, residues[i].C, residues[i+1].N))

    return structure


def parse_fasta(filepath: str) -> str:
    """Parse un fichier FASTA et retourne la séquence."""
    with open(filepath, 'r') as f:
        lines = f.readlines()

    sequence = ''
    for line in lines:
        line = line.strip()
        if not line.startswith('>'):
            sequence += line

    return sequence.upper()


