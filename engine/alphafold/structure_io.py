def write_pdb(structure: ProteinStructure, filepath: str,
              title: str = "ALPHAFOLD Harmonic Deterministic Model"):
    """
    Écrit une structure au format PDB.

    Args:
        structure: ProteinStructure à écrire
        filepath: chemin du fichier de sortie
        title: titre pour l'en-tête
    """
    lines = []
    lines.append(f"HEADER    {title}")
    lines.append(f"REMARK    Generated by ALPHAFOLD Harmonic Engine")
    lines.append(f"REMARK    Method: Deterministic ABC Fractional Dynamics")
    lines.append(f"REMARK    Sequence: {structure.sequence}")

    atom_serial = 1
    for res in structure.residues:
        res_name = AA1TO3.get(res.aa.code1, 'UNK')
        res_idx = res.index + 1

        # Backbone atoms in standard order
        for atom_name in ['N', 'CA', 'C', 'O']:
            pos = getattr(res, atom_name)
            if np.all(pos == 0):
                continue
            line = _format_atom(atom_serial, atom_name, res_name, res_idx,
                               pos[0], pos[1], pos[2])
            lines.append(line)
            atom_serial += 1

        # Sidechain atoms
        for atom_name, pos in sorted(res.sidechain.items()):
            if np.all(pos == 0):
                continue
            line = _format_atom(atom_serial, atom_name, res_name, res_idx,
                               pos[0], pos[1], pos[2])
            lines.append(line)
            atom_serial += 1

    lines.append("END\n")

    with open(filepath, 'w') as f:
        f.write('\n'.join(lines))


def _format_atom(serial: int, name: str, res_name: str, res_idx: int,
                 x: float, y: float, z: float,
                 occupancy: float = 1.0, temp_factor: float = 0.0,
                 element: str = '') -> str:
    """Formate une ligne ATOM PDB."""
    if not element:
        element = name[0] if name[0] in 'CNOS' else 'C'

    return (f"ATOM  {serial:5d} {name:<4s} {res_name:3s} A{res_idx:4d}    "
            f"{x:8.3f}{y:8.3f}{z:8.3f}"
            f"{occupancy:6.2f}{temp_factor:6.2f}          "
            f"{element:>2s}")


