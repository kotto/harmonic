def compute_tm_score(mobile: np.ndarray, target: np.ndarray) -> float:
    """
    Calcule le TM-score entre deux ensembles de points Cα.

    TM-score = max [1/L_target * Σ_i 1/(1 + (d_i/d_0(L))²)]
    où d_0(L) = 1.24 * ∛(L - 15) - 1.8

    Args:
        mobile: coordonnées Cα mobiles (N×3)
        target: coordonnées Cα cibles (N×3)

    Returns:
        TM-score (0-1, plus c'est proche de 1, meilleur c'est)
    """
    from .backbone import superimpose

    L = len(target)
    if L < 12:
        return 0.0

    # Facteur d'échelle
    d0 = 1.24 * (L - 15) ** (1.0 / 3.0) - 1.8
    d0 = max(d0, 0.5)

    # Superposer
    mobile_aligned = superimpose(mobile, target)

    # Calculer le TM-score
    d = np.sqrt(np.sum((mobile_aligned - target) ** 2, axis=1))
    tm = np.mean(1.0 / (1.0 + (d / d0) ** 2))

    return float(tm)


def compute_gdt_ts(mobile: np.ndarray, target: np.ndarray) -> float:
    """
    Calcule le GDT-TS (Global Distance Test — Total Score).

    GDT-TS = moyenne des fractions de résidus sous 1, 2, 4, 8 Å
    après superposition optimale.

    Args:
        mobile: coordonnées Cα mobiles (N×3)
        target: coordonnées Cα cibles (N×3)

    Returns:
        GDT-TS score (0-1)
    """
    from .backbone import superimpose

    mobile_aligned = superimpose(mobile, target)
    d = np.sqrt(np.sum((mobile_aligned - target) ** 2, axis=1))

    thresholds = [1.0, 2.0, 4.0, 8.0]
    fractions = [np.mean(d <= t) for t in thresholds]
    gdt = np.mean(fractions)

    return float(gdt)


def compare_structures(predicted: ProteinStructure,
                       reference: ProteinStructure) -> Dict:
    """
    Compare deux structures protéiques et retourne les métriques.

    Args:
        predicted: structure prédite
        reference: structure de référence (expérimentale)

    Returns:
        Dictionnaire avec RMSD, TM-score, GDT-TS
    """
    ca_pred = predicted.ca_trace
    ca_ref = reference.ca_trace

    if len(ca_pred) != len(ca_ref):
        # Aligner sur les résidus communs
        min_len = min(len(ca_pred), len(ca_ref))
        ca_pred = ca_pred[:min_len]
        ca_ref = ca_ref[:min_len]

    rmsd_val = rmsd(ca_pred, ca_ref)
    tm = compute_tm_score(ca_pred, ca_ref)
    gdt = compute_gdt_ts(ca_pred, ca_ref)

    return {
        'rmsd_angstrom': round(rmsd_val, 3),
        'tm_score': round(tm, 4),
        'gdt_ts': round(gdt, 4),
        'n_residues_compared': len(ca_pred),
    }


