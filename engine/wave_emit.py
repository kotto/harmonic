def emit_typescript(program: Program) -> str:
    """
    Convertit un programme harmonique en TypeScript.

    Même structure que JavaScript, avec des types annotés sur les Assign
    (nombre si le RHS est un MathOp, chaîne si StringLit, sinon any).
    """
    lines = [
        "// Generated by Wave Emit — Langage harmonique → TypeScript",
        "",
    ]
    defined: set = set()
    for stmt in program.statements:
        ts = _stmt_ts(stmt, indent=0, defined=defined)
        if ts:
            lines.append(ts)
    return "\n".join(lines)


def _ts_type(expr) -> str:
    """Infère le type TypeScript d'une expression."""
    if isinstance(expr, MathOp):
        return "number"
    if isinstance(expr, Literal):
        return "number"
    if isinstance(expr, StringLit):
        return "string"
    if isinstance(expr, FunctionCall):
        return "any"
    return "any"


def _stmt_ts(stmt, indent: int = 0, defined: Optional[set] = None) -> str:
    """Convertit un statement en TypeScript."""
    if defined is None:
        defined = set()
    pad = "    " * indent
    if isinstance(stmt, Assign):
        if stmt.name in defined:
            return f"{pad}{stmt.name} = {_expr_js(stmt.value)};"
        defined.add(stmt.name)
        return (f"{pad}let {stmt.name}: {_ts_type(stmt.value)} = "
                f"{_expr_js(stmt.value)};")
    if isinstance(stmt, Return):
        return f"{pad}return {_expr_js(stmt.value)};"
    if isinstance(stmt, CodeBlock):
        return "\n".join(_stmt_ts(s, indent, defined) for s in stmt.body)
    if isinstance(stmt, IfStmt):
        lines = [f"{pad}if ({_expr_js(stmt.condition)}) {{"]
        for s in stmt.then_body:
            lines.append(_stmt_ts(s, indent + 1, defined))
        if stmt.else_body is not None and stmt.else_body:
            lines.append(f"{pad}}} else {{")
            for s in stmt.else_body:
                lines.append(_stmt_ts(s, indent + 1, defined))
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    if isinstance(stmt, WhileStmt):
        lines = [f"{pad}while ({_expr_js(stmt.condition)}) {{"]
        for s in stmt.body:
            lines.append(_stmt_ts(s, indent + 1, defined))
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    if isinstance(stmt, FunctionDef):
        params = ", ".join(stmt.params)
        lines = [f"{pad}function {stmt.name}({params}): any {{"]
        for p in stmt.params:
            defined.add(p)
        for s in stmt.body:
            lines.append(_stmt_ts(s, indent + 1, defined))
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    if isinstance(stmt, ForStmt):
        lines = [f"{pad}for (const {stmt.target} of {_expr_js(stmt.iterable)}) {{"]
        for s in stmt.body:
            lines.append(_stmt_ts(s, indent + 1, defined))
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    if isinstance(stmt, AugAssign):
        op_map = {'ADD': '+=', 'SUB': '-=', 'MUL': '*=', 'DIV': '/='}
        sym = op_map.get(stmt.op, stmt.op)
        return f"{pad}{stmt.name} {sym} {_expr_js(stmt.value)};"
    # Store/Query → commentaires (bridge serveur)
    if isinstance(stmt, Store):
        return f"{pad}// store: {stmt.hologram}.store_raw(...)"
    if isinstance(stmt, Query):
        return f"{pad}// query: {stmt.name} = {stmt.hologram}.query(...)"
    return ""


def emit(program: Program, target: str = 'python') -> str:
    """
    Dispatch générique : convertit vers la cible demandée.

    Args:
        program: AST wave_ir
        target: 'python', 'javascript', 'typescript' (ou alias 'js', 'ts')

    Returns:
        code source de la cible
    """
    target = target.lower()
    if target in ('python', 'py'):
        return emit_python(program)
    if target in ('javascript', 'js'):
        return emit_javascript(program)
    if target in ('typescript', 'ts'):
        return emit_typescript(program)
    raise ValueError(f"Cible inconnue: {target} (python, javascript, typescript)")


