def emit_javascript(program: Program) -> str:
    """
    Convertit un programme harmonique en JavaScript.

    Les nœuds ondulatoires sont émis en commentaires documentés
    (le bridge wave_lang est côté serveur) ; les nœuds computationnels
    sont émis en JS natif.
    """
    lines = [
        "// Generated by Wave Emit — Langage harmonique → JavaScript",
        "",
    ]
    defined: set = set()
    for stmt in program.statements:
        js = _stmt_js(stmt, indent=0, defined=defined)
        if js:
            lines.append(js)
    return "\n".join(lines)


def _stmt_js(stmt, indent: int = 0, defined: Optional[set] = None) -> str:
    """Convertit un statement en JavaScript."""
    if defined is None:
        defined = set()
    pad = "    " * indent
    if isinstance(stmt, Assign):
        # 'let' uniquement à la première définition (pas de re-déclaration)
        if stmt.name in defined:
            return f"{pad}{stmt.name} = {_expr_js(stmt.value)};"
        defined.add(stmt.name)
        return f"{pad}let {stmt.name} = {_expr_js(stmt.value)};"
    elif isinstance(stmt, Store):
        return (f"{pad}// HolographicMemory store: {stmt.hologram}"
                f".store_raw({_expr_js(stmt.value)})")
    elif isinstance(stmt, Query):
        return (f"{pad}// HolographicMemory query: {stmt.name} = "
                f"{stmt.hologram}.query({_expr_js(stmt.value)})")
    elif isinstance(stmt, Return):
        return f"{pad}return {_expr_js(stmt.value)};"
    elif isinstance(stmt, CodeBlock):
        return "\n".join(_stmt_js(s, indent, defined) for s in stmt.body)
    elif isinstance(stmt, IfStmt):
        lines = [f"{pad}if ({_expr_js(stmt.condition)}) {{"]
        for s in stmt.then_body:
            lines.append(_stmt_js(s, indent + 1, defined))
        if stmt.else_body is not None and stmt.else_body:
            lines.append(f"{pad}}} else {{")
            for s in stmt.else_body:
                lines.append(_stmt_js(s, indent + 1, defined))
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    elif isinstance(stmt, WhileStmt):
        lines = [f"{pad}while ({_expr_js(stmt.condition)}) {{"]
        for s in stmt.body:
            lines.append(_stmt_js(s, indent + 1, defined))
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    elif isinstance(stmt, FunctionDef):
        params = ", ".join(stmt.params)
        lines = [f"{pad}function {stmt.name}({params}) {{"]
        # Les paramètres sont déjà déclarés (pas de 'let' dans le corps)
        for p in stmt.params:
            defined.add(p)
        for s in stmt.body:
            lines.append(_stmt_js(s, indent + 1, defined))
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    elif isinstance(stmt, ForStmt):
        lines = [f"{pad}for (const {stmt.target} of {_expr_js(stmt.iterable)}) {{"]
        for s in stmt.body:
            lines.append(_stmt_js(s, indent + 1, defined))
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    elif isinstance(stmt, AugAssign):
        op_map = {'ADD': '+=', 'SUB': '-=', 'MUL': '*=', 'DIV': '/='}
        sym = op_map.get(stmt.op, stmt.op)
        return f"{pad}{stmt.name} {sym} {_expr_js(stmt.value)};"
    return ""


def _expr_js(expr) -> str:
    """Convertit une expression en JavaScript."""
    if isinstance(expr, Var):
        return expr.name
    elif isinstance(expr, Literal):
        v = expr.value
        return repr(int(v)) if isinstance(v, float) and v.is_integer() else repr(v)
    elif isinstance(expr, StringLit):
        return repr(expr.value)
    elif isinstance(expr, MathOp):
        if expr.right is not None and expr.op in _BINARY_OPS_JS:
            return _BINARY_OPS_JS[expr.op](_expr_js(expr.left),
                                           _expr_js(expr.right))
        if expr.op in _UNARY_OPS_JS:
            return _UNARY_OPS_JS[expr.op](_expr_js(expr.left))
        args = [_expr_js(expr.left)]
        if expr.right is not None:
            args.append(_expr_js(expr.right))
        return f"{expr.op.lower()}({', '.join(args)})"
    elif isinstance(expr, FunctionCall):
        args = ", ".join(_expr_js(a) for a in expr.args)
        return f"{expr.name}({args})"
    # Nœuds ondulatoires → commentaires documentés
    elif isinstance(expr, Encode):
        return f"/* ψ = encode('{expr.text}') */ null"
    elif isinstance(expr, Decode):
        return f"/* decode(ψ) */ null"
    elif isinstance(expr, (Bind, Unbind, Superpose, Resonance, Emerge,
                           Oppose, Amplify, BindMany, Normalize, Rotate,
                           Interfere, Diffract, FilterLP, FilterHP, FilterBP,
                           PhaseShift)):
        return f"/* {type(expr).__name__} (wave_lang, serveur) */ null"
    elif isinstance(expr, ListLiteral):
        items = ", ".join(_expr_js(i) for i in expr.items)
        return f"[{items}]"
    elif isinstance(expr, Subscript):
        return f"{_expr_js(expr.obj)}[{_expr_js(expr.index)}]"
    elif isinstance(expr, TernaryExpr):
        return (f"({_expr_js(expr.condition)} ? {_expr_js(expr.if_true)} "
                f": {_expr_js(expr.if_false)})")
    elif isinstance(expr, LambdaExpr):
        params = ", ".join(expr.params)
        return f"({params}) => {_expr_js(expr.body)}"
    elif isinstance(expr, RawCode):
        return expr.text
    return f"/* <? {type(expr).__name__} ?> */ null"


