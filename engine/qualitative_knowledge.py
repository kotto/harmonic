def assigner_angle(mot: str, secteur: str, offset: float = 0.0) -> float:
    """
    Assigne un angle a un mot dans son secteur semantique.
    
    Les mots proches dans le meme secteur recoivent des angles proches.
    L'offset permet de positionner le mot finement dans le secteur.
    
    Args:
        mot: le mot a positionner
        secteur: nom du secteur semantique
        offset: decalage dans le secteur (0.0 = debut, 1.0 = fin)
    
    Returns:
        angle en degres
    """
    debut, fin, _ = SECTORS[secteur]
    # Utiliser le hash du mot pour un offset deterministe si non specifie
    if offset == 0.0:
        offset = (hash(mot) % 100) / 100.0
    return debut + offset * (fin - debut)


def angle_to_wave(angle_deg: float, rayon: float = 1.0) -> Tuple[float, float]:
    """Convertit un angle en vecteur d'onde (kx, ky)."""
    rad = math.radians(angle_deg)
    return rayon * math.cos(rad), rayon * math.sin(rad)


