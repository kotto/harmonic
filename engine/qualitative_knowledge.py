def build_natural_waves(vocab_words=None):
    word_order = {}
    position = 0
    for sujet, rel, objet, _ in KNOWLEDGE_BASE:
        for mot in sujet.split() + rel.split() + objet.split():
            mot = mot.strip('.,!?;:')
            if len(mot) >= 2 and mot not in word_order:
                word_order[mot] = position
                position += 1
    for w in {'le','la','les','de','des','du','un','une','et','est','a','dans','que','qui','pas','ne','sur','pour','avec','ce','cette','par','au','aux','en','plus','moins','tout','tous','son','sa','ses'}:
        if w not in word_order: word_order[w] = position; position += 1
    words = sorted(word_order, key=word_order.get)
    word_to_id = {w: i for i, w in enumerate(words)}
    n = len(words)
    kx = np.zeros(n); ky = np.zeros(n)
    for word, order in word_order.items():
        idx = word_to_id[word]
        # Linear angle: adjacent IDs = adjacent angles.
        # No phi. The order in the knowledge base IS the meaning.
        angle = (order * PHI * 2 * math.pi / (n + 100)) % (2 * math.pi)
        kx[idx] = math.cos(angle); ky[idx] = math.sin(angle)
    return kx, ky, word_to_id

class MemoireOndulatoire:
    def __init__(self, nx=128, ny=128):
        self.nx, self.ny = nx, ny
        x = np.linspace(-math.pi, math.pi, nx)
        y = np.linspace(-math.pi, math.pi, ny)
        self.xx, self.yy = np.meshgrid(x, y, indexing='ij')
        self.H = np.zeros((nx, ny), dtype=np.complex128)
        self.n_experiences = 0
    def enregistrer(self, kx_w, ky_w, amplitude=1.0):
        onde = np.exp(1j * (kx_w * self.xx + ky_w * self.yy))
        self.H += amplitude * onde
        self.n_experiences += 1
    def enregistrer_texte(self, texte, kx, ky, w2i, amplitude=0.5):
        for mot in texte.lower().split():
            mot = mot.strip('.,!?;:')
            if mot in w2i:
                idx = w2i[mot]
                self.enregistrer(kx[idx], ky[idx], amplitude)
    def resonance(self, kx_w, ky_w):
        onde_ref = np.exp(-1j * (kx_w * self.xx + ky_w * self.yy))
        corr = np.sum(self.H * onde_ref)
        return float(np.abs(corr) / (self.nx * self.ny))
    def resonance_complexe(self, kx_w, ky_w):
        onde_ref = np.exp(-1j * (kx_w * self.xx + ky_w * self.yy))
        return complex(np.sum(self.H * onde_ref) / (self.nx * self.ny))
    @property
    def energie(self):
        return float(np.sum(np.abs(self.H) ** 2))

